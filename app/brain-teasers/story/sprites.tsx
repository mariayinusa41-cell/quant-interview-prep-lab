export function PixelSprite({
  sprite,
  palette,
  dimmed,
  lit,
  wide,
}: {
  sprite: string;
  palette: Palette;
  dimmed?: boolean;
  lit?: boolean;
  wide?: boolean;
}) {
  const grid = GRIDS[sprite] ?? GRIDS.person;
  const h = grid.length;
  const w = grid[0].length;

  const colorFor = (code: number) => {
    switch (code) {
      case 1:
        return palette.a;
      case 2:
        return palette.b;
      case 3:
        return OUTLINE;
      case 4:
        return EYE;
      case 5:
        return palette.c;
      case 6:
        return palette.d ?? palette.a;
      case 7:
        return palette.e ?? OUTLINE;
      case 8:
        return palette.f ?? "#f4f0e8";
      default:
        return null;
    }
  };

  const cls = ["story-sprite-svg", dimmed ? "is-dimmed" : "", lit ? "is-lit" : "", wide || w > 10 ? "is-wide" : ""]
    .filter(Boolean)
    .join(" ");

  return (
    <svg viewBox={`0 0 ${w} ${h}`} className={cls} shapeRendering="crispEdges">
      {grid.map((row, y) =>
        row.map((code, x) => {
          const fill = colorFor(code);
          if (!fill) return null;
          return <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={fill} />;
        })
      )}
    </svg>
  );
}
